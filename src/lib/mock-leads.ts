const SORT_MAP: Record<string, keyof Lead> = {
  businessName: 'businessName',
  contactName: 'contactName',
  address: 'address',
  city: 'city',
  state: 'state',
  leadStatus: 'leadStatus',
  priority: 'priority',
  industry: 'industry',
  estimatedDealValue: 'estimatedDealValue',
  createdDate: 'createdDate',
  updatedDate: 'updatedDate',
  nextFollowUpDate: 'nextFollowUpDate',
  lastContactedDate: 'lastContactedDate',
};

function toText(value: unknown) {
  return String(value ?? '').toLowerCase();
}

function scorePriority(priority: Lead['priority']) {
  if (priority === 'Urgent') return 4;
  if (priority === 'Hot') return 3;
  if (priority === 'Warm') return 2;
  return 1;
}

function inMonth(value: string, monthPrefix: string) {
  if (!value) return false;
  return value.startsWith(monthPrefix);
}

