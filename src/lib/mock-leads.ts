export function getFilteredMockLeads(query: LeadQuery): Lead[] {
  const search = toText(query.search);
  const status = query.status || '';
  const priority = query.priority || '';
  const city = toText(query.city);
  const state = toText(query.state);
  const industry = query.industry || '';
  const sort = query.sort || 'createdDate';
  const dir = query.dir === 'asc' ? 1 : -1;

  const filtered = MOCK_LEADS.filter((lead) => {
    if (search) {
      const blob = [lead.businessName, lead.contactName, lead.phone, lead.city, lead.industry].map(toText).join(' ');
      if (!blob.includes(search)) return false;
    }
    if (status && lead.leadStatus !== status) return false;
    if (priority && lead.priority !== priority) return false;
    if (city && !toText(lead.city).includes(city)) return false;
    if (state && !toText(lead.state).includes(state)) return false;
    if (industry && lead.industry !== industry) return false;
    return true;
  });

  const key = SORT_MAP[sort] || 'createdDate';

  filtered.sort((a, b) => {
    const av = a[key];
    const bv = b[key];

    if (key === 'priority') {
      return (scorePriority(av as Lead['priority']) - scorePriority(bv as Lead['priority'])) * dir;
    }

    if (typeof av === 'number' || av === null || typeof bv === 'number' || bv === null) {
      const an = Number(av ?? 0);
      const bn = Number(bv ?? 0);
      return (an - bn) * dir;
    }

    return String(av ?? '').localeCompare(String(bv ?? '')) * dir;
  });

  return filtered;
}

export function buildMockDashboardStats(): DashboardStats {
  const today = new Date().toISOString().slice(0, 10);
  const thisMonth = today.slice(0, 7);

  const totalLeads = MOCK_LEADS.length;
  const newLeads = MOCK_LEADS.filter((l) => l.leadStatus === 'New').length;
  const contactedLeads = MOCK_LEADS.filter((l) =>
    ['Contacted', 'No answer', 'Interested', 'Follow up needed', 'Meeting scheduled', 'Proposal sent'].includes(l.leadStatus)
  ).length;
  const interestedLeads = MOCK_LEADS.filter((l) => l.leadStatus === 'Interested').length;
  const demoSentLeads = MOCK_LEADS.filter((l) => l.leadStatus === 'Demo website sent').length;
  const followUpDueToday = MOCK_LEADS.filter((l) =>
    l.nextFollowUpDate && l.nextFollowUpDate <= today && !['Won', 'Lost', 'Not a fit'].includes(l.leadStatus)
  ).length;
  const wonDeals = MOCK_LEADS.filter((l) => l.leadStatus === 'Won').length;
  const lostDeals = MOCK_LEADS.filter((l) => l.leadStatus === 'Lost').length;

  const monthlyEstimatedValue = MOCK_LEADS.reduce((sum, lead) => {
    if (['Lost', 'Not a fit'].includes(lead.leadStatus)) return sum;
    if (!lead.estimatedDealValue || lead.estimatedDealValue <= 0) return sum;
    if (!inMonth(lead.createdDate, thisMonth)) return sum;
    return sum + lead.estimatedDealValue;
  }, 0);

  const wonThisMonthValue = MOCK_LEADS.reduce((sum, lead) => {
    if (lead.leadStatus !== 'Won') return sum;
    if (!lead.estimatedDealValue || lead.estimatedDealValue <= 0) return sum;
    if (!inMonth(lead.updatedDate, thisMonth)) return sum;
    return sum + lead.estimatedDealValue;
  }, 0);

  const hotLeads = getFilteredMockLeads({}).filter((l) => ['Hot', 'Urgent'].includes(l.priority) && !['Won', 'Lost', 'Not a fit'].includes(l.leadStatus)).slice(0, 5);
  const upcomingFollowUps = getFilteredMockLeads({}).filter((l) => l.nextFollowUpDate && l.nextFollowUpDate >= today && !['Won', 'Lost', 'Not a fit'].includes(l.leadStatus)).sort((a, b) => a.nextFollowUpDate.localeCompare(b.nextFollowUpDate)).slice(0, 8);

  const recentActivity: Activity[] = MOCK_LEADS.slice(0, 10).map((lead, index) => ({
    id: index + 1,
    leadId: lead.id,
    type: 'note',
    description: `Followed up with ${lead.contactName}`,
    createdDate: lead.updatedDate,
    businessName: lead.businessName,
  }));

  return {
    totalLeads,
    newLeads,
    contactedLeads,
    interestedLeads,
    demoSentLeads,
    followUpDueToday,
    wonDeals,
    lostDeals,
    monthlyEstimatedValue,
    wonThisMonthValue,
    hotLeads,
    recentActivity,
    upcomingFollowUps,
    routesToday: 0,
    stopsToday: 0,
    completedRoutesThisMonth: 0,
    stopsCompletedThisMonth: 0,
  };
}
